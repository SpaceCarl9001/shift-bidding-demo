// Packs lib/schedule.js and lib/coaching.js (the same code the API uses) into demo/lib-bundle.js
// for the browser demo, as window.DemoLib = { schedule, coaching }. Run: node demo/build.js
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const wrap = (name, file) => `modules[${JSON.stringify(name)}] = (function () {
  const module = { exports: {} }, exports = module.exports;
  const require = n => modules[n.replace(/^\\.\\//, "")];
${fs.readFileSync(path.join(root, file), "utf8")}
  return module.exports;
})();`;
const out = `// Generated by demo/build.js from lib/schedule.js and lib/coaching.js. Do not edit by hand.
(function () {
const modules = {};
${wrap("schedule", "lib/schedule.js")}
${wrap("coaching", "lib/coaching.js")}
window.DemoLib = modules;
})();
`;
fs.writeFileSync(path.join(__dirname, "lib-bundle.js"), out);
console.log("wrote demo/lib-bundle.js");

-- Shift trades: after auto assign and before the schedule is pushed to Assembled, two agents in
-- the same LOB trade their assigned shifts for good. The partner accepts, an admin approves, and
-- approving exchanges the two assignments. Nothing goes to Assembled until the admin pushes.
-- (Day swaps in swaps.sql are different: temporary, for specific dates, after the push.)
-- Run after swaps.sql: Supabase Dashboard > SQL Editor > New query > paste > Run.
-- Safe to re-run. Runs as one transaction: if anything errors, nothing is changed.
--
-- Agents ask for and accept trades only while their LOB's trade window is open (swap_windows,
-- kind 'trade'; day swaps have their own 'swap' window). Once it closes, trades the partner never
-- answered are auto declined (auto_declined = true): on the next trade board or admin load, and
-- right away when an admin closes, changes or removes the window. Trades already accepted (waiting
-- for an admin) stay.
-- Agents never read or write shift_trades directly: they use the security definer functions
-- below, which only show or change trades they are part of. Admins manage the table.

begin;

create table if not exists public.shift_trades (
  id bigint generated by default as identity primary key,
  lob text not null,
  requester_id bigint not null references public.agents (id) on delete cascade,
  partner_id bigint not null references public.agents (id) on delete cascade,
  requester_shift_id bigint references public.shift_shells (id) on delete set null,  -- shifts at request time
  partner_shift_id bigint references public.shift_shells (id) on delete set null,
  note text,
  status text not null default 'pending_partner'
    check (status in ('pending_partner', 'declined', 'cancelled', 'pending_admin', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  partner_responded_at timestamptz,
  decided_at timestamptz,
  decided_by text,
  admin_note text
);

alter table public.shift_trades add column if not exists auto_declined boolean not null default false;

alter table public.shift_trades enable row level security;

do $$
declare p record;
begin
  for p in select policyname from pg_policies where schemaname = 'public' and tablename = 'shift_trades'
  loop
    execute format('drop policy %I on public.shift_trades', p.policyname);
  end loop;
end $$;

create policy "admins read shift trades" on public.shift_trades
  for select to authenticated using (is_admin());
create policy "swap approvers change shift trades" on public.shift_trades
  for update to authenticated using (has_perm('swaps')) with check (has_perm('swaps'));

-- Auto declines trades still waiting for the partner in any LOB whose trade window is not open
-- (closed, not open yet, or removed). Returns how many. Safe for anyone to call: it only applies
-- that rule.
create or replace function public.expire_closed_trades() returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_n integer;
begin
  update shift_trades t
     set status = 'declined', auto_declined = true, partner_responded_at = now()
   where t.status = 'pending_partner'
     and not exists (select 1 from swap_windows w
                      where w.lob = t.lob and w.kind = 'trade' and now() >= w.opens_at and now() <= w.closes_at);
  get diagnostics v_n = row_count;
  return v_n;
end $$;

-- When an admin changes a trade window: before (so a closed window that is opened again does not
-- bring old unanswered trades back) and after (so closing or removing it declines them now).
create or replace function public.trade_window_expire() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  perform expire_closed_trades();
  return case when tg_op = 'DELETE' then old else new end;
end $$;

drop trigger if exists trade_window_expire_before on public.swap_windows;
create trigger trade_window_expire_before before update or delete on public.swap_windows
  for each row when (old.kind = 'trade') execute function public.trade_window_expire();
drop trigger if exists trade_window_expire_after on public.swap_windows;
create trigger trade_window_expire_after after insert or update or delete on public.swap_windows
  for each statement execute function public.trade_window_expire();

-- An agent's trades, and whether their assigned shift is already in Assembled (day swaps need
-- that). Null for removed or unlinked logins. Before their LOB's results are published
-- (published_results in swaps.sql): no trades, only "published": false.
-- Not stable: it first auto declines unanswered trades whose window closed.
create or replace function public.trade_board() returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare
  v_me agents%rowtype;
begin
  perform expire_closed_trades();
  select * into v_me from agents where email = lower(auth.jwt() ->> 'email') limit 1;
  if v_me.id is null or v_me.excluded then
    return null;
  end if;
  if not lob_published(v_me.lob) then
    return jsonb_build_object('published', false, 'window', null, 'pushed', false, 'trades', '[]'::jsonb);
  end if;
  return jsonb_build_object(
    'published', true,
    'window', (select jsonb_build_object('opens_at', w.opens_at, 'closes_at', w.closes_at,
                 'open', now() >= w.opens_at and now() <= w.closes_at)
               from swap_windows w where w.lob = v_me.lob and w.kind = 'trade'),
    'pushed', coalesce((select x.pushed_at is not null from assignments x where x.agent_id = v_me.id limit 1), false),
    'trades', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', t.id, 'status', t.status, 'auto_declined', t.auto_declined, 'note', t.note, 'admin_note', t.admin_note, 'created_at', t.created_at,
        'mine', t.requester_id = v_me.id,
        'other_name', case when t.requester_id = v_me.id then p.name else q.name end,
        'my_shift', case when t.requester_id = v_me.id then (to_jsonb(rs) - 'set_name') else (to_jsonb(ps) - 'set_name') end,
        'their_shift', case when t.requester_id = v_me.id then (to_jsonb(ps) - 'set_name') else (to_jsonb(rs) - 'set_name') end
      ) order by t.created_at desc)
      from shift_trades t
      join agents q on q.id = t.requester_id
      join agents p on p.id = t.partner_id
      left join shift_shells rs on rs.id = t.requester_shift_id
      left join shift_shells ps on ps.id = t.partner_shift_id
      where t.requester_id = v_me.id or t.partner_id = v_me.id), '[]'::jsonb)
  );
end $$;

-- Agent A asks agent B to trade assigned shifts for good.
create or replace function public.request_trade(p_partner_id bigint, p_note text default null)
returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_me agents%rowtype;
  v_partner agents%rowtype;
  v_my_shift bigint;
  v_partner_shift bigint;
  v_id bigint;
begin
  select * into v_me from agents where email = lower(auth.jwt() ->> 'email') limit 1;
  if v_me.id is null then raise exception 'Your login is not linked to an agent record.'; end if;
  if v_me.excluded then raise exception 'You are not part of this shift bid.'; end if;
  if not lob_published(v_me.lob) then raise exception 'The % results are not published yet.', v_me.lob; end if;
  if not my_trading_open() then raise exception 'Shift trades are not open for % right now.', v_me.lob; end if;

  select * into v_partner from agents where id = p_partner_id;
  if v_partner.id = v_me.id then raise exception 'You cannot trade with yourself.'; end if;
  if v_partner.id is null or v_partner.excluded or v_partner.lob is distinct from v_me.lob then
    raise exception 'You can only trade with someone in your own LOB.';
  end if;

  select shift_id into v_my_shift from assignments where agent_id = v_me.id limit 1;
  select shift_id into v_partner_shift from assignments where agent_id = v_partner.id limit 1;
  if v_my_shift is null then raise exception 'You do not have an assigned shift to trade yet.'; end if;
  if v_partner_shift is null then raise exception '% does not have an assigned shift yet.', v_partner.name; end if;
  if v_my_shift = v_partner_shift then raise exception 'You and % have the same shift, so there is nothing to trade.', v_partner.name; end if;

  if exists (
    select 1 from shift_trades t
    where t.status in ('pending_partner', 'pending_admin')
      and (t.requester_id in (v_me.id, v_partner.id) or t.partner_id in (v_me.id, v_partner.id))
  ) then
    raise exception 'You or % already have a shift trade waiting. Finish or cancel it first.', v_partner.name;
  end if;

  insert into shift_trades (lob, requester_id, partner_id, requester_shift_id, partner_shift_id, note)
  values (v_me.lob, v_me.id, v_partner.id, v_my_shift, v_partner_shift, nullif(trim(p_note), ''))
  returning id into v_id;
  return v_id;
end $$;

-- Agent B accepts (sends it to the admin) or declines a trade they were asked for.
-- Declining always works; accepting only while the swap window is open.
create or replace function public.respond_trade(p_id bigint, p_accept boolean)
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_me bigint;
begin
  select id into v_me from agents where email = lower(auth.jwt() ->> 'email') and not excluded limit 1;
  if p_accept and not lob_published(my_lob()) then raise exception 'Your results are not published yet.'; end if;
  if p_accept and not my_trading_open() then
    raise exception 'Shift trades are not open right now, so this trade cannot be accepted. You can still decline it.';
  end if;
  update shift_trades
     set status = case when p_accept then 'pending_admin' else 'declined' end,
         partner_responded_at = now()
   where id = p_id and partner_id = v_me and status = 'pending_partner';
  if not found then raise exception 'This trade request is no longer waiting for you.'; end if;
end $$;

-- The requester withdraws a trade that has not been decided yet.
create or replace function public.cancel_trade(p_id bigint)
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_me bigint;
begin
  select id into v_me from agents where email = lower(auth.jwt() ->> 'email') limit 1;
  update shift_trades set status = 'cancelled'
   where id = p_id and requester_id = v_me and status in ('pending_partner', 'pending_admin');
  if not found then raise exception 'This trade can no longer be cancelled.'; end if;
end $$;

-- Admin approves or rejects. Approving exchanges the two agents' assignments in one step, but
-- only if both still have the shifts they had when they asked and neither is in Assembled yet.
create or replace function public.decide_trade(p_id bigint, p_approve boolean, p_note text default null)
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_t shift_trades%rowtype;
  v_a assignments%rowtype;
  v_b assignments%rowtype;
begin
  -- Runs as the owner (it changes assignments), so it checks the permission itself.
  if not has_perm('swaps') then raise exception 'You do not have permission to approve or reject trades.' using errcode = '42501'; end if;
  select * into v_t from shift_trades where id = p_id for update;
  if v_t.id is null then raise exception 'That trade does not exist.'; end if;
  if v_t.status <> 'pending_admin' then raise exception 'This trade is not waiting for approval any more.'; end if;

  if p_approve then
    select * into v_a from assignments where agent_id = v_t.requester_id limit 1 for update;
    select * into v_b from assignments where agent_id = v_t.partner_id limit 1 for update;
    if v_a.id is null or v_b.id is null then
      raise exception 'One of these agents no longer has an assigned shift. Reject this trade.';
    end if;
    if v_a.shift_id is distinct from v_t.requester_shift_id or v_b.shift_id is distinct from v_t.partner_shift_id then
      raise exception 'Their assigned shifts have changed since they asked (auto assign was re-run or another trade was approved). Reject this trade and ask them to request it again.';
    end if;
    if v_a.pushed_at is not null or v_b.pushed_at is not null then
      raise exception 'Their schedule is already in Assembled, so a trade here would not reach it. Use a day swap instead, or reject this trade.';
    end if;
    update assignments set shift_id = v_t.partner_shift_id where id = v_a.id;
    update assignments set shift_id = v_t.requester_shift_id where id = v_b.id;
  end if;

  update shift_trades
     set status = case when p_approve then 'approved' else 'rejected' end,
         decided_at = now(), decided_by = lower(auth.jwt() ->> 'email'), admin_note = nullif(trim(p_note), '')
   where id = p_id;
end $$;

revoke execute on function public.trade_window_expire() from anon, public;

revoke execute on function
  public.expire_closed_trades(),
  public.trade_board(),
  public.request_trade(bigint, text),
  public.respond_trade(bigint, boolean),
  public.cancel_trade(bigint),
  public.decide_trade(bigint, boolean, text)
from anon, public;

grant execute on function
  public.expire_closed_trades(),
  public.trade_board(),
  public.request_trade(bigint, text),
  public.respond_trade(bigint, boolean),
  public.cancel_trade(bigint),
  public.decide_trade(bigint, boolean, text)
to authenticated;

commit;

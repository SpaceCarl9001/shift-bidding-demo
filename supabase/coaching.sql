-- Coach groups: each LOB's coaches with their schedules, and which coach each agent is with.
-- The app shares a LOB's agents out between its coaches (about the same number each, matched to
-- the coach's schedule) on the Coaches tab, and can then move each agent into their coach's team
-- in Assembled (api/coaching.js).
-- Run after rls-policies.sql: Supabase Dashboard > SQL Editor > New query > paste > Run.
-- Safe to re-run. Runs as one transaction: if anything errors, nothing is changed.
--
-- All admins can read these. Changing coaches and coach groups needs the "roster" permission
-- (Roster & ranks); moving people between teams in Assembled needs "push" (checked by the server).
-- Agents never read these tables. They see only their own coach's name, through my_coach(), and
-- only once both the LOB's results (published_results, swaps.sql) and its coach groups
-- (coach_lob_settings.coaches_published_at) are published. Run after swaps.sql.

begin;

create table if not exists public.coaches (
  id bigint generated by default as identity primary key,
  lob text not null,
  name text not null,
  assembled_team_id text,     -- their coach group team in Assembled, e.g. "Sales Coaches > Coach Sam"
  days text not null,         -- like shift shells: comma separated weekdays, 0 = Sunday
  start_local text not null,  -- "HH:MM"
  end_local text not null,    -- "HH:MM"; earlier than start_local means overnight
  timezone text not null default 'America/New_York',
  created_at timestamptz not null default now()
);

create table if not exists public.coach_assignments (
  agent_id bigint primary key references public.agents (id) on delete cascade,
  coach_id bigint not null references public.coaches (id) on delete cascade,
  overlap_minutes integer,    -- minutes a week the agent's shift and the coach's schedule overlap
  saved_at timestamptz not null default now(),
  saved_by text default lower(auth.jwt() ->> 'email'),
  synced_at timestamptz       -- when the agent was moved into the coach's team in Assembled
);

-- How many coaches each LOB has, set on the Coaches tab. The app suggests that many coach
-- schedules from the LOB's shift shells (lib/coaching.js suggestSchedules).
create table if not exists public.coach_lob_settings (
  lob text primary key,
  coach_count integer check (coach_count between 1 and 50),
  updated_at timestamptz not null default now()
);
alter table public.coach_lob_settings alter column coach_count drop not null;
-- Set when an admin publishes the LOB's coach groups to its agents (Coaches tab); null hides them.
alter table public.coach_lob_settings add column if not exists coaches_published_at timestamptz;
alter table public.coach_lob_settings add column if not exists coaches_published_by text;

-- Coach bids: coaches bid on coach shells in their own bid group, "<LOB> Coaches" (for example
-- "Support Coaches"), which works like any LOB. A coach added to that group keeps it: lob_locked
-- stops a sync from Assembled from moving them back to their Assembled team.
alter table public.agents add column if not exists lob_locked boolean not null default false;
-- The coach's own person record (in the coach bid group), once their bid result sets their schedule.
alter table public.coaches add column if not exists agent_id bigint references public.agents (id) on delete set null;

alter table public.coaches enable row level security;
alter table public.coach_assignments enable row level security;
alter table public.coach_lob_settings enable row level security;

do $$
declare p record;
begin
  for p in select tablename, policyname from pg_policies
           where schemaname = 'public' and tablename in ('coaches', 'coach_assignments', 'coach_lob_settings')
  loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end $$;

create policy "admins read coaches" on public.coaches
  for select to authenticated using (is_admin());
create policy "roster editors manage coaches" on public.coaches
  for all to authenticated using (has_perm('roster')) with check (has_perm('roster'));
create policy "admins read coach assignments" on public.coach_assignments
  for select to authenticated using (is_admin());
create policy "roster editors manage coach assignments" on public.coach_assignments
  for all to authenticated using (has_perm('roster')) with check (has_perm('roster'));
create policy "admins read coach settings" on public.coach_lob_settings
  for select to authenticated using (is_admin());
create policy "roster editors manage coach settings" on public.coach_lob_settings
  for all to authenticated using (has_perm('roster')) with check (has_perm('roster'));

-- Saves a LOB's coach groups in one step: replaces the coach of every agent in p_rows.
-- p_rows: [{"agent_id": 1, "coach_id": 2, "overlap_minutes": 2400}, ...]. Every agent and coach
-- must be in p_lob. Agents in the LOB who are not in p_rows lose their coach.
create or replace function public.replace_coach_assignments(p_lob text, p_rows jsonb)
returns void
language plpgsql security invoker set search_path = public as $$
begin
  if not has_perm('roster') then
    raise exception 'You do not have permission to change coach groups.' using errcode = '42501';
  end if;
  if exists (
    select 1 from jsonb_to_recordset(coalesce(p_rows, '[]'::jsonb)) as r(agent_id bigint, coach_id bigint)
    left join agents a on a.id = r.agent_id
    left join coaches c on c.id = r.coach_id
    where a.id is null or c.id is null or a.lob is distinct from p_lob or c.lob is distinct from p_lob
  ) then
    raise exception 'Every agent and coach must be in %.', p_lob;
  end if;

  delete from coach_assignments where agent_id in (select id from agents where lob = p_lob);
  insert into coach_assignments (agent_id, coach_id, overlap_minutes)
  select r.agent_id, r.coach_id, r.overlap_minutes
  from jsonb_to_recordset(coalesce(p_rows, '[]'::jsonb)) as r(agent_id bigint, coach_id bigint, overlap_minutes integer);
end $$;

-- The signed-in agent's coach: { "name": ... }, or null until both the LOB's results and its coach
-- groups are published, or when they have no coach. Shows nothing about anyone else.
create or replace function public.my_coach() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_me agents%rowtype;
  v_name text;
begin
  select * into v_me from agents where email = lower(auth.jwt() ->> 'email') limit 1;
  if v_me.id is null or v_me.excluded then return null; end if;
  if not lob_published(v_me.lob) then return null; end if;
  if not exists (select 1 from coach_lob_settings where lob = v_me.lob and coaches_published_at is not null) then return null; end if;
  select c.name into v_name from coach_assignments x join coaches c on c.id = x.coach_id
   where x.agent_id = v_me.id and c.lob = v_me.lob;
  if v_name is null then return null; end if;
  return jsonb_build_object('name', v_name);
end $$;

-- For a signed-in coach (a person in a coach bid group, linked to their coach record by its bid
-- result): the agents in their coach group, with each agent's assigned shift. Empty until the
-- LOB's coach groups are published (finalized). Nothing about other coaches' agents.
create or replace function public.my_coach_agents() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_me agents%rowtype;
  v_coach coaches%rowtype;
begin
  select * into v_me from agents where email = lower(auth.jwt() ->> 'email') limit 1;
  if v_me.id is null or v_me.excluded then return null; end if;
  select * into v_coach from coaches where agent_id = v_me.id limit 1;
  if v_coach.id is null then return null; end if;
  if not exists (select 1 from coach_lob_settings where lob = v_coach.lob and coaches_published_at is not null) then
    return jsonb_build_object('lob', v_coach.lob, 'published', false, 'agents', '[]'::jsonb);
  end if;
  return jsonb_build_object('lob', v_coach.lob, 'published', true, 'agents', coalesce((
    select jsonb_agg(jsonb_build_object('name', a.name, 'shift', (to_jsonb(s) - 'set_name' - 'seats' - 'id' - 'lob')) order by a.name)
    from coach_assignments x
    join agents a on a.id = x.agent_id and not a.excluded and a.lob = v_coach.lob
    left join assignments asg on asg.agent_id = a.id
    left join shift_shells s on s.id = asg.shift_id
    where x.coach_id = v_coach.id), '[]'::jsonb));
end $$;

revoke execute on function public.replace_coach_assignments(text, jsonb) from anon, public;
grant execute on function public.replace_coach_assignments(text, jsonb) to authenticated;
revoke execute on function public.my_coach() from anon, public;
revoke execute on function public.my_coach_agents() from anon, public;
grant execute on function public.my_coach_agents() to authenticated;
grant execute on function public.my_coach() to authenticated;

commit;

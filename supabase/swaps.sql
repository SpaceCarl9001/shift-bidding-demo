-- Agent A asks agent B to swap rest days: A gives p_give (A works, B is off) and takes p_take
-- (A is off, B works), both in the same Monday-to-Sunday week.
create or replace function public.request_day_swap(p_partner_id bigint, p_give date, p_take date, p_note text default null)
returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_me agents%rowtype;
  v_partner agents%rowtype;
  v_my_shift bigint;
  v_partner_shift bigint;
  v_my_days text;
  v_partner_days text;
  v_id bigint;
begin
  select * into v_me from agents where email = lower(auth.jwt() ->> 'email') limit 1;
  if v_me.id is null then raise exception 'Your login is not linked to an agent record.'; end if;
  if v_me.excluded then raise exception 'You are not part of this shift bid.'; end if;
  if not lob_published(v_me.lob) then raise exception 'The % results are not published yet.', v_me.lob; end if;

  select * into v_partner from agents where id = p_partner_id;
  if v_partner.id = v_me.id then raise exception 'You cannot swap with yourself.'; end if;
  if v_partner.id is null or v_partner.excluded or v_partner.lob is distinct from v_me.lob then
    raise exception 'You can only swap with someone in your own LOB.';
  end if;

  select shift_id into v_my_shift from assignments where agent_id = v_me.id limit 1;
  select shift_id into v_partner_shift from assignments where agent_id = v_partner.id limit 1;
  if v_my_shift is null then raise exception 'You do not have an assigned shift to swap yet.'; end if;
  if v_partner_shift is null then raise exception '% does not have an assigned shift yet.', v_partner.name; end if;
  if v_my_shift = v_partner_shift then raise exception 'You and % have the same shift, so there is nothing to swap.', v_partner.name; end if;
  select days into v_my_days from shift_shells where id = v_my_shift;
  select days into v_partner_days from shift_shells where id = v_partner_shift;

  if p_give is null or p_take is null or p_give = p_take then raise exception 'Pick two different days.'; end if;
  if least(p_give, p_take) < current_date - 1 then raise exception 'The swap cannot be in the past.'; end if;
  if date_trunc('week', p_give) <> date_trunc('week', p_take) then
    raise exception 'Both days must be in the same Monday-to-Sunday week, so your weekly hours stay the same.';
  end if;
  if not shell_works(v_my_days, p_give) then
    raise exception 'You are not scheduled on %. The day you give must be one of your work days.', to_char(p_give, 'Dy Mon DD');
  end if;
  if shell_works(v_partner_days, p_give) then
    raise exception '% also works on %, so they cannot take it.', v_partner.name, to_char(p_give, 'Dy Mon DD');
  end if;
  if shell_works(v_my_days, p_take) then
    raise exception 'You already work on %. The day you take must be one of your days off.', to_char(p_take, 'Dy Mon DD');
  end if;
  if not shell_works(v_partner_days, p_take) then
    raise exception '% is off on % too, so there is no shift to take.', v_partner.name, to_char(p_take, 'Dy Mon DD');
  end if;

  if exists (
    select 1 from swap_requests r
    where r.status in ('pending_partner', 'pending_admin', 'approved')
      and (r.requester_id in (v_me.id, v_partner.id) or r.partner_id in (v_me.id, v_partner.id))
      and ((r.give_date is not null and (r.give_date in (p_give, p_take) or r.take_date in (p_give, p_take)))
        or (r.give_date is null and r.start_date <= greatest(p_give, p_take) and r.end_date >= least(p_give, p_take)))
  ) then
    raise exception 'You or % already have a swap on one of these days.', v_partner.name;
  end if;

  insert into swap_requests (lob, requester_id, partner_id, requester_shift_id, partner_shift_id,
                             start_date, end_date, give_date, take_date, note)
  values (v_me.lob, v_me.id, v_partner.id, v_my_shift, v_partner_shift,
          least(p_give, p_take), greatest(p_give, p_take), p_give, p_take, nullif(trim(p_note), ''))
  returning id into v_id;
  return v_id;
end $$;

-- Agent B accepts (sends it to the admin) or declines a swap they were asked for.
create or replace function public.respond_swap(p_id bigint, p_accept boolean)
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_me bigint;
begin
  select id into v_me from agents where email = lower(auth.jwt() ->> 'email') and not excluded limit 1;
  if p_accept and not lob_published(my_lob()) then raise exception 'Your results are not published yet.'; end if;
  update swap_requests
     set status = case when p_accept then 'pending_admin' else 'declined' end,
         partner_responded_at = now()
   where id = p_id and partner_id = v_me and status = 'pending_partner';
  if not found then raise exception 'This swap request is no longer waiting for you.'; end if;
end $$;

-- The requester withdraws a swap that has not been decided yet.
create or replace function public.cancel_swap(p_id bigint)
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_me bigint;
begin
  select id into v_me from agents where email = lower(auth.jwt() ->> 'email') limit 1;
  update swap_requests set status = 'cancelled'
   where id = p_id and requester_id = v_me and status in ('pending_partner', 'pending_admin');
  if not found then raise exception 'This swap can no longer be cancelled.'; end if;
end $$;


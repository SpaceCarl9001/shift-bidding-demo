-- Shift swaps between two agents in the same LOB.
-- Run after rls-policies.sql and save-functions.sql: Supabase Dashboard > SQL Editor > New query > paste > Run.
-- Safe to re-run. Runs as one transaction: if anything errors, nothing is changed.
--
-- Flow: agent A asks agent B to swap rest days (pending_partner) -> B accepts (pending_admin)
-- or declines -> an admin approves (the app moves each agent's own working day in Assembled
-- onto their day off, as Shift Swap) or rejects. The requester can cancel while pending.
--
-- A rest-day swap is two days in the same Monday-to-Sunday week:
--   give_date: A works and B is off. After the swap A is off and B works it.
--   take_date: A is off and B works.  After the swap A works it and B is off.
-- Each agent keeps the same number of working days and their own shift times and length, so
-- weekly hours stay the same (40). Day swaps are always open. Shift trades (shift-trades.sql)
-- are the ones with a window: swap_windows rows of kind 'trade'.
--
-- Agents see shifts, and can ask for or accept trades and day swaps, only once an admin publishes
-- their LOB's auto assign results (published_results, Results tab).
--
-- Agents never read or write swap_requests directly: they use the security definer functions
-- below, which only ever show or change swaps they are part of. Admins manage the table.

begin;

create table if not exists public.swap_requests (
  id bigint generated by default as identity primary key,
  lob text not null,
  requester_id bigint not null references public.agents (id) on delete cascade,
  partner_id bigint not null references public.agents (id) on delete cascade,
  requester_shift_id bigint references public.shift_shells (id) on delete set null,  -- shifts at request time
  partner_shift_id bigint references public.shift_shells (id) on delete set null,
  start_date date not null,
  end_date date not null,
  note text,
  status text not null default 'pending_partner'
    check (status in ('pending_partner', 'declined', 'cancelled', 'pending_admin', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  partner_responded_at timestamptz,
  decided_at timestamptz,
  decided_by text,
  admin_note text,
  result jsonb           -- what the approval changed in Assembled
);

-- Rest-day swaps (see above). Older one-day swaps have neither and use start_date/end_date.
alter table public.swap_requests add column if not exists give_date date;
alter table public.swap_requests add column if not exists take_date date;

alter table public.swap_requests enable row level security;

-- True when a shell with these weekdays ("1,2,3", 0 = Sunday) works on that date.
create or replace function public.shell_works(p_days text, p_date date) returns boolean
language sql immutable set search_path = public as $$
  select extract(dow from p_date)::int::text = any (string_to_array(replace(coalesce(p_days, ''), ' ', ''), ','));
$$;

do $$
declare p record;
begin
  for p in select policyname from pg_policies where schemaname = 'public' and tablename = 'swap_requests'
  loop
    execute format('drop policy %I on public.swap_requests', p.policyname);
  end loop;
end $$;

create policy "admins read swap requests" on public.swap_requests
  for select to authenticated using (is_admin());
create policy "swap approvers change swap requests" on public.swap_requests
  for update to authenticated using (has_perm('swaps')) with check (has_perm('swaps'));

-- When each LOB's agents may ask for and accept trades ("trade") and day swaps ("swap").
-- Set on the admin Swaps tab.
create table if not exists public.swap_windows (
  lob text not null,
  kind text not null default 'trade',
  opens_at timestamptz not null,
  closes_at timestamptz not null,
  updated_at timestamptz not null default now(),
  constraint swap_window_closes_after_opens check (closes_at > opens_at),
  primary key (lob, kind)
);

-- Projects that had one window per LOB: that window becomes the trade window, and each LOB can
-- now also have a separate day swap window.
alter table public.swap_windows add column if not exists kind text not null default 'trade';
do $$
begin
  if not exists (select 1 from pg_constraint where conrelid = 'public.swap_windows'::regclass and conname = 'swap_windows_kind_check') then
    alter table public.swap_windows add constraint swap_windows_kind_check check (kind in ('trade', 'swap'));
  end if;
  if (select array_length(i.indkey::int2[], 1) from pg_index i
      where i.indrelid = 'public.swap_windows'::regclass and i.indisprimary) = 1 then
    alter table public.swap_windows drop constraint swap_windows_pkey;
    alter table public.swap_windows add primary key (lob, kind);
  end if;
end $$;

alter table public.swap_windows enable row level security;

do $$
declare p record;
begin
  for p in select policyname from pg_policies where schemaname = 'public' and tablename = 'swap_windows'
  loop
    execute format('drop policy %I on public.swap_windows', p.policyname);
  end loop;
end $$;

create policy "admins read swap windows" on public.swap_windows
  for select to authenticated using (is_admin());
create policy "window editors manage swap windows" on public.swap_windows
  for all to authenticated using (has_perm('windows')) with check (has_perm('windows'));
create policy "agents read own lob swap window" on public.swap_windows
  for select to authenticated using (lob = my_lob());

-- True while the signed-in agent's LOB day swap window is open (never for removed agents).
create or replace function public.my_swapping_open() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from swap_windows w
    where w.lob = my_lob() and w.kind = 'swap' and now() >= w.opens_at and now() <= w.closes_at
  );
$$;

-- True while the signed-in agent's LOB trade window is open (never for removed agents).
create or replace function public.my_trading_open() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from swap_windows w
    where w.lob = my_lob() and w.kind = 'trade' and now() >= w.opens_at and now() <= w.closes_at
  );
$$;

-- Auto assign results a LOB's agents may see. Until an admin publishes a LOB (Results tab),
-- its agents see neither their own assigned shift nor anyone else's, and cannot ask for trades
-- or day swaps. A LOB with no row here is not published.
create table if not exists public.published_results (
  lob text primary key,
  published_at timestamptz not null default now(),
  published_by text default lower(auth.jwt() ->> 'email')
);

alter table public.published_results enable row level security;

do $$
declare p record;
begin
  for p in select policyname from pg_policies where schemaname = 'public' and tablename = 'published_results'
  loop
    execute format('drop policy %I on public.published_results', p.policyname);
  end loop;
end $$;

create policy "admins read published results" on public.published_results
  for select to authenticated using (is_admin());
create policy "auto assigners publish results" on public.published_results
  for all to authenticated using (has_perm('assign')) with check (has_perm('assign'));

-- True when this LOB's results are published.
create or replace function public.lob_published(p_lob text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from published_results where lob = p_lob);
$$;

-- Everything an agent's swap screen needs: their own shift, colleagues in their LOB who have a
-- shift (name and shift only, without admin-only set names), and the swaps they are part of. Null for removed or unlinked logins.
-- Before their LOB's results are published: no shifts and no swaps, only "published": false.
create or replace function public.swap_board() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_me agents%rowtype;
begin
  select * into v_me from agents where email = lower(auth.jwt() ->> 'email') limit 1;
  if v_me.id is null or v_me.excluded then
    return null;
  end if;
  if not lob_published(v_me.lob) then
    return jsonb_build_object('published', false,
      'me', jsonb_build_object('id', v_me.id, 'name', v_me.name, 'lob', v_me.lob, 'shift', null),
      'colleagues', '[]'::jsonb, 'requests', '[]'::jsonb);
  end if;

  return jsonb_build_object(
    'published', true,
    'window', (select jsonb_build_object('opens_at', w.opens_at, 'closes_at', w.closes_at,
                 'open', now() >= w.opens_at and now() <= w.closes_at)
               from swap_windows w where w.lob = v_me.lob and w.kind = 'swap'),
    'me', jsonb_build_object(
      'id', v_me.id, 'name', v_me.name, 'lob', v_me.lob,
      'shift', (select (to_jsonb(s) - 'set_name') from assignments x join shift_shells s on s.id = x.shift_id
                where x.agent_id = v_me.id limit 1)),
    'colleagues', coalesce((
      select jsonb_agg(jsonb_build_object('id', a.id, 'name', a.name, 'shift', (to_jsonb(s) - 'set_name')) order by a.name)
      from agents a
      join assignments x on x.agent_id = a.id
      join shift_shells s on s.id = x.shift_id
      where a.lob = v_me.lob and not a.excluded and a.id <> v_me.id), '[]'::jsonb),
    'requests', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', r.id, 'status', r.status, 'start_date', r.start_date, 'end_date', r.end_date,
        'give_date', r.give_date, 'take_date', r.take_date,
        'note', r.note, 'admin_note', r.admin_note, 'created_at', r.created_at,
        'mine', r.requester_id = v_me.id,
        'other_name', case when r.requester_id = v_me.id then p.name else q.name end,
        'my_shift', case when r.requester_id = v_me.id then (to_jsonb(rs) - 'set_name') else (to_jsonb(ps) - 'set_name') end,
        'their_shift', case when r.requester_id = v_me.id then (to_jsonb(ps) - 'set_name') else (to_jsonb(rs) - 'set_name') end
      ) order by r.created_at desc)
      from swap_requests r
      join agents q on q.id = r.requester_id
      join agents p on p.id = r.partner_id
      left join shift_shells rs on rs.id = r.requester_shift_id
      left join shift_shells ps on ps.id = r.partner_shift_id
      where r.requester_id = v_me.id or r.partner_id = v_me.id), '[]'::jsonb)
  );
end $$;


-- Tables used by the shift bidding app, for reference and for rebuilding a fresh project.
-- Reconstructed from the live project's API schema on 2026-09-23. The API does not expose
-- unique constraints or ON DELETE rules, so those below are what the app code relies on.
--
-- Fresh project setup order:
--   1. supabase/schema.sql
--   2. supabase/rls-policies.sql
--   3. supabase/save-functions.sql

create table if not exists public.agents (
  id bigint generated by default as identity primary key,
  assembled_id text,
  name text,
  email text unique,          -- sync upserts on email (on_conflict=email)
  lob text,
  rank integer,               -- 1 bids first; null sorts last
  assembled_agent_id text,    -- needed to push shifts into Assembled
  excluded boolean not null default false  -- removed from bidding by an admin; sync leaves it alone
);

create table if not exists public.shift_shells (
  id bigint generated by default as identity primary key,
  lob text not null,
  schedule text,              -- human readable summary, e.g. "Mon,Tue 08:00 to 17:00 America/New_York"
  seats integer not null default 1,
  days text,                  -- comma separated weekday numbers, 0 = Sunday
  start_local text,           -- "HH:MM" in timezone
  end_local text,             -- "HH:MM"; earlier than start_local means overnight
  timezone text,              -- IANA name, e.g. America/New_York
  set_name text               -- optional group, e.g. "A" or "B" (shown as Set A / Set B)
);

create table if not exists public.bid_windows (
  id bigint generated by default as identity primary key,
  lob text not null,          -- one window per LOB (replace_bid_window keeps it that way)
  opens_at timestamptz not null,
  closes_at timestamptz not null,
  require_full_ranking boolean not null default true  -- agents must rank every shell in the LOB
);

create table if not exists public.bids2 (
  id bigint generated by default as identity primary key,
  agent_id bigint references public.agents (id),
  shift_id bigint references public.shift_shells (id),
  priority integer not null   -- 1 is the agent's top choice
);

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  agent_id bigint references public.agents (id),
  shift_id bigint references public.shift_shells (id),
  run_at timestamptz default now(),
  pushed_at timestamptz,      -- set once the shifts are in Assembled
  push_error text
);

create table if not exists public.app_settings (
  key text primary key,
  value text
);

-- Existing projects created before these columns:
alter table public.agents add column if not exists excluded boolean not null default false;
alter table public.bid_windows add column if not exists require_full_ranking boolean not null default true;
alter table public.shift_shells add column if not exists set_name text;
-- Agents approved for a schedule accommodation are placed before everyone else in auto assign.
alter table public.agents add column if not exists accommodation boolean not null default false;
-- Accommodation tiers: Tier 1 is placed first, then Tier 2, then Tier 3.
alter table public.agents add column if not exists accommodation_tier smallint check (accommodation_tier between 1 and 3);
